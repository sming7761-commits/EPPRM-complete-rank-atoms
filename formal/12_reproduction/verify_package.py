"""EPPRM package verification. Use --allow-partial only before main experiment finishes.
Final strict mode requires 6000 raw paths, 48000 complete records and matching traces.
SHA256SUMS.txt must be generated by build_manifest.py AFTER the last write.
"""
from __future__ import annotations
import csv,sys,hashlib,collections,os
from pathlib import Path
import numpy as np
ROOT=Path(__file__).resolve().parents[1]
METHODS=['EP_PRM_736','Profiled_CCTM_fair','OLS_PlugIn_PRM','Gaussian_GLR','Gaussian_CUSUM','Conformal_CUSUM','Old_K8','Oracle_PRM']
DISTS=['gaussian','t5','exp_centered','skew_mixture']

def read_csv(p):
    with p.open(newline='',encoding='utf-8') as f:return list(csv.DictReader(f))

def fail(msg):raise AssertionError(msg)

def verify(partial=False,deep=False):
    errors=[];counts={}
    def chk(ok,msg):
        if not ok:errors.append(msg)
    seedtables={}
    for name in ('pilot','calibration','formal_test'):
        rows=read_csv(ROOT/'04_seed_manifests'/f'{name}_seeds.csv')
        seedtables[name]=rows
        counts[name+'_manifest']=len(rows)
    chk(len(seedtables['pilot'])==800,'pilot seed count !=800')
    chk(len(seedtables['calibration'])==20000,'calibration seed count !=20000')
    chk(len(seedtables['formal_test'])==6000,'formal seed count !=6000')
    sets={k:{int(r['seed']) for r in v} for k,v in seedtables.items()}
    for k,v in sets.items():chk(len(v)==len(seedtables[k]),f'{k} duplicates')
    chk(not (sets['pilot']&sets['calibration'] or sets['pilot']&sets['formal_test'] or sets['calibration']&sets['formal_test']),'seed leakage')
    counts['raw_files']=0
    for r in seedtables['formal_test']:
        dist=r['distribution'];sc=r['scenario'];rep=int(r['replicate'])
        fp=ROOT/'05_raw_data'/sc/dist/f'{rep:04d}.npz'
        if not fp.exists():continue
        counts['raw_files']+=1
        if deep:
            with np.load(fp,allow_pickle=False) as z:
                chk(int(z['seed'])==int(r['seed']),f'seed mismatch {fp}')
                chk(len(z['reference_A'])==113 and len(z['reference_B'])==625 and len(z['online_states'])==601,f'raw shape mismatch {fp}')
                eps=z['online_innovations'];on=z['online_states'];chk(len(eps)==600 and np.allclose(on[1:]-.9*on[:-1],eps,atol=3e-14),f'innovation mismatch {fp}')
    chk(partial or counts['raw_files']==6000,'raw not 6000')
    counts['calibration_method_maxima']=0
    for dist in DISTS:
        p=ROOT/'05_raw_data/calibration'/f'max_{dist}.csv'
        if not p.exists():continue
        rows=read_csv(p)
        keys=[(int(r['rep']),r['method']) for r in rows]
        chk(len(keys)==len(set(keys)),f'cal duplicate {dist}')
        chk(all(int(r['seed']) in sets['calibration'] for r in rows),f'cal seed intrusion {dist}')
        counts['calibration_method_maxima']+=len(rows)
        chk(partial or len(rows)==20000,f'cal count !=20000 {dist}')
    counts['formal_method_records']=0;counts['valid_method_records']=0;counts['complete_trajectory_pairs']=0
    summ=ROOT/'07_tidy_results/method_records.csv'
    if summ.exists():
        rows=read_csv(summ)
        keys=[(r['trajectory_id'],r['method']) for r in rows]
        chk(len(keys)==len(set(keys)),'duplicated method rows')
        counts['formal_method_records']=len(rows)
        groups=collections.defaultdict(set)
        for r in rows:
            id=r['trajectory_id'];m=r['method'];dist=r['distribution'];sc=r['scenario'];rep=int(r['replicate']);first=int(r['first_alarm'])
            groups[id].add(m)
            chk(int(r['seed']) in sets['formal_test'],f'nonformal seed {id}')
            chk(m in METHODS,f'unknown method {m}')
            chk(int(r['prefault_alarm'])==int(0<first<357),f'prefault mismatch {id} {m}')
            chk(int(r['detected_after_change'])==int(sc=='fault' and first>=357),f'detection mismatch {id} {m}')
            trace=ROOT/'06_method_traces'/dist/sc/f'{rep:04d}_{m}.npz'
            chk(trace.exists(),f'missing trace {trace}')
            if trace.exists():
                with np.load(trace,allow_pickle=False) as z:
                    v=z['value'];cr=z['crossing'];threshold=float(z['threshold']);status=str(z['status'])
                    chk(len(v)==601 and len(cr)==601,f'trace shape {id} {m}')
                    chk(abs(float(r['threshold'])-threshold)<1e-12,f'threshold mismatch {id} {m}')
                    if np.isfinite(v).all():
                        hh=np.flatnonzero(v[1:]>=threshold)
                        calc=int(hh[0]+1) if len(hh) else 0
                        chk(first==calc,f'alarm mismatch {id} {m}')
                        chk(np.array_equal(cr,(v>=threshold).astype(np.int8)),f'crossing mismatch {id} {m}')
                    elif first>=0:chk(False,f'incomplete trace but nonerror summary {id} {m}')
            if first>=0 and r['numeric_status'] not in ('UNKNOWN','ERROR'):
                counts['valid_method_records']+=1
        counts['complete_trajectory_pairs']=sum(1 for ms in groups.values() if ms==set(METHODS))
        chk(partial or counts['formal_method_records']==48000,'formal records != 48000')
        chk(partial or counts['valid_method_records']==48000,'valid records != 48000')
        chk(partial or counts['complete_trajectory_pairs']==6000,'incomplete per-trajectory method pairing')
    else:chk(partial,'method_records.csv missing')
    sha=ROOT/'SHA256SUMS.txt'
    if sha.exists():
        mismatches=[];nsha=0
        for line in sha.read_text().splitlines():
            if not line.strip():continue
            h,rel=line.split('  ',1);fp=ROOT/rel
            if not fp.exists() or hashlib.sha256(fp.read_bytes()).hexdigest()!=h:mismatches.append(rel)
            nsha+=1
        chk(not mismatches,'HASH MISMATCH: '+repr(mismatches[:8]))
        counts['hashed_files']=nsha
        # Exclude nonportable, regenerable interpreter/Numba caches from scientific SHA inventory.
        expected={str(p.relative_to(ROOT)) for p in ROOT.rglob('*')
                  if p.is_file() and p.name not in ('SHA256SUMS.txt','MANIFEST.csv','integrity_report.md')
                  and '__pycache__' not in p.parts and p.suffix not in ('.pyc','.nbi','.nbc')
                  and p.name != '.lock' and '.tmp.' not in p.name}
        documented={line.split('  ',1)[1] for line in sha.read_text().splitlines() if line.strip()}
        chk(expected==documented,'Hash manifest file-set mismatch '+str(len(expected-documented))+' not listed')
    else:chk(False,'SHA256SUMS missing')
    status='PASS_PARTIAL_STRUCTURE_ONLY' if partial and not errors else 'PASS_COMPLETE' if not errors else 'FAIL'
    print('VERIFY',status,'counts',counts,'errors',errors[:12])
    return status,counts,errors

if __name__=='__main__':
    status,counts,errors=verify('--allow-partial' in sys.argv,'--deep' in sys.argv)
    sys.exit(1 if errors else 0)
